using System;
using System.Collections.Generic;
using DG.Tweening;
using TMPro;
using UnityEngine;
using UnityEngine.UI;
using Logic.Scripts.GameDomain.Services.Skills;
using Logic.Scripts.GameDomain.MVC.ExplorationLoadout;
using UnityEngine.EventSystems;

public class ExplorationLoadoutUIView : MonoBehaviour, IExplorationLoadoutView
{
    [Header("Root")]
    [SerializeField] private GameObject _rootPanel;
    [SerializeField] private Button _closeButton;
    [SerializeField] private bool _autoGenerateDebugCanvas;

    [Header("Loadout Slots")]
    [Tooltip("Container da Erza — 4 SkillFrames são gerados aqui ao abrir o painel.")]
    [SerializeField] private Transform _playerSlotsContainer;
    [Tooltip("Container do livro — 4 SkillFrames são gerados aqui ao abrir o painel.")]
    [SerializeField] private Transform _bookSlotsContainer;

    [Header("Catalog")]
    [Tooltip("Parent transform where skill frames are spawned (Grid/Layout group in your scene).")]
    [SerializeField] private Transform _catalogContainer;
    [Tooltip("SkillFrame.prefab — must include LoadoutSkillFrameView.")]
    [SerializeField] private LoadoutSkillFrameView _skillFramePrefab;
    [Tooltip("Opcional. Dropdown TMP no prefab da cena (mesma ordem que ExplorationLoadoutSkillFilter).")]
    [SerializeField] private TMP_Dropdown _skillCategoryDropdown;
    [Tooltip("Opcional. Dropdown TMP para filtrar por divindade.")]
    [SerializeField] private TMP_Dropdown _divinityCategoryDropdown;

    [Header("Details")]
    [SerializeField] private TMP_Text _detailNameText;
    [SerializeField] private TMP_Text _detailDivinityText;
    [SerializeField] private TMP_Text _detailSkillTypeText;
    [SerializeField] private TMP_Text _detailDescriptionText;
    [SerializeField] private TMP_Text _detailPowerText;
    [SerializeField] private TMP_Text _detailCostText;
    [SerializeField] private TMP_Text _detailRangeText;
    [SerializeField] private Image _detailBackgroundImage;
    [SerializeField] private Image _detailFrameImage;
    [SerializeField] private Image _detailIconImage;

    private ISkillVisualCatalog _visualCatalog;
    private Action<ExplorationLoadoutSkillFilter> _onCatalogFilterChanged;
    private Action<ExplorationLoadoutDivinityFilter> _onDivinityFilterChanged;
    private Action<int> _onPlayerSlotClicked;
    private Action<int> _onBookSlotClicked;
    private readonly List<LoadoutSkillFrameView> _catalogItems = new List<LoadoutSkillFrameView>(16);
    private readonly List<LoadoutSkillFrameView> _playerSlotFrames = new List<LoadoutSkillFrameView>(4);
    private readonly List<LoadoutSkillFrameView> _bookSlotFrames = new List<LoadoutSkillFrameView>(4);

    private void Awake()
    {
        if (_autoGenerateDebugCanvas)
            BuildDebugCanvasIfNeeded();
        EnsureHiddenOnSceneLoad();
    }

    private void EnsureHiddenOnSceneLoad()
    {
        SetVisible(false);
    }

    public bool IsVisible => _rootPanel != null && _rootPanel.activeSelf;

    public void Init(ISkillVisualCatalog visualCatalog = null)
    {
        _visualCatalog = visualCatalog;
        SetVisible(false);
    }

    public void RegisterCallbacks(Action onClose, Action<int> onPlayerSlotClicked, Action<int> onBookSlotClicked,
        Action<ExplorationLoadoutSkillFilter> onCatalogFilterChanged = null,
        Action<ExplorationLoadoutDivinityFilter> onDivinityFilterChanged = null)
    {
        if (_closeButton != null)
        {
            _closeButton.onClick.RemoveAllListeners();
            _closeButton.onClick.AddListener(() => onClose?.Invoke());
        }

        _onPlayerSlotClicked = onPlayerSlotClicked;
        _onBookSlotClicked = onBookSlotClicked;

        _onCatalogFilterChanged = onCatalogFilterChanged;
        _onDivinityFilterChanged = onDivinityFilterChanged;
        WireSkillCategoryDropdown();
        WireDivinityCategoryDropdown();
    }

    private void WireSkillCategoryDropdown()
    {
        if (_skillCategoryDropdown == null) return;
        _skillCategoryDropdown.onValueChanged.RemoveListener(OnSkillCategoryDropdownValueChanged);
        _skillCategoryDropdown.ClearOptions();
        var opts = new List<string>(5);
        for (int i = 0; i <= (int)ExplorationLoadoutSkillFilter.Buff; i++)
            opts.Add(ExplorationLoadoutSkillFilterUtil.DisplayLabel((ExplorationLoadoutSkillFilter)i));
        _skillCategoryDropdown.AddOptions(opts);
        _skillCategoryDropdown.SetValueWithoutNotify(0);
        _skillCategoryDropdown.onValueChanged.AddListener(OnSkillCategoryDropdownValueChanged);
    }

    private void OnSkillCategoryDropdownValueChanged(int index)
    {
        if (index < 0 || index > (int)ExplorationLoadoutSkillFilter.Buff) return;
        _onCatalogFilterChanged?.Invoke((ExplorationLoadoutSkillFilter)index);
    }

    private void WireDivinityCategoryDropdown()
    {
        if (_divinityCategoryDropdown == null) return;
        _divinityCategoryDropdown.onValueChanged.RemoveListener(OnDivinityCategoryDropdownValueChanged);
        _divinityCategoryDropdown.ClearOptions();
        var opts = new List<string>(6);
        for (int i = 0; i <= (int)ExplorationLoadoutDivinityFilter.Iara; i++)
            opts.Add(ExplorationLoadoutDivinityFilterUtil.DisplayLabel((ExplorationLoadoutDivinityFilter)i));
        _divinityCategoryDropdown.AddOptions(opts);
        _divinityCategoryDropdown.SetValueWithoutNotify(0);
        _divinityCategoryDropdown.onValueChanged.AddListener(OnDivinityCategoryDropdownValueChanged);
    }

    private void OnDivinityCategoryDropdownValueChanged(int index)
    {
        if (index < 0 || index > (int)ExplorationLoadoutDivinityFilter.Iara) return;
        _onDivinityFilterChanged?.Invoke((ExplorationLoadoutDivinityFilter)index);
    }

    public void SetVisible(bool visible)
    {
        if (_rootPanel != null) _rootPanel.SetActive(visible);
    }

    public void RebuildLoadoutSlots(int slotCount, Func<SkillLoadoutUnitType, int, SkillDataSO> getSkillForSlot)
    {
        RebuildUnitLoadoutSlots(SkillLoadoutUnitType.Player, _playerSlotsContainer, _playerSlotFrames,
            slotCount, getSkillForSlot, _onPlayerSlotClicked);
        RebuildUnitLoadoutSlots(SkillLoadoutUnitType.Book, _bookSlotsContainer, _bookSlotFrames,
            slotCount, getSkillForSlot, _onBookSlotClicked);
        FinalizeLoadoutSlotLayout(_playerSlotsContainer);
        FinalizeLoadoutSlotLayout(_bookSlotsContainer);
    }

    void RebuildUnitLoadoutSlots(
        SkillLoadoutUnitType unitType,
        Transform container,
        List<LoadoutSkillFrameView> frameList,
        int slotCount,
        Func<SkillLoadoutUnitType, int, SkillDataSO> getSkillForSlot,
        Action<int> onSlotClicked)
    {
        frameList.Clear();
        if (container == null || _skillFramePrefab == null || slotCount <= 0) return;

        for (int i = container.childCount - 1; i >= 0; i--)
            Destroy(container.GetChild(i).gameObject);

        for (int i = 0; i < slotCount; i++)
        {
            int slotIndex = i;
            SkillDataSO skill = getSkillForSlot?.Invoke(unitType, slotIndex);
            LoadoutSkillFrameView frame = Instantiate(_skillFramePrefab, container);
            frameList.Add(frame);
            frame.Bind(skill, _visualCatalog, _ => onSlotClicked?.Invoke(slotIndex));
            frame.SetSlotSelected(false);
        }
    }

    static void FinalizeLoadoutSlotLayout(Transform container)
    {
        if (container is not RectTransform rt) return;
        LayoutRebuilder.ForceRebuildLayoutImmediate(rt);
    }

    public void SetSelectedSlot(SkillLoadoutUnitType unitType, int slotIndex)
    {
        ClearSlotSelection();
        List<LoadoutSkillFrameView> frames = unitType == SkillLoadoutUnitType.Book ? _bookSlotFrames : _playerSlotFrames;
        if (slotIndex < 0 || slotIndex >= frames.Count) return;
        LoadoutSkillFrameView selected = frames[slotIndex];
        if (selected != null) selected.SetSlotSelected(true);
    }

    public void ClearSlotSelection()
    {
        SetSlotSelectionState(_playerSlotFrames, false);
        SetSlotSelectionState(_bookSlotFrames, false);
    }

    static void SetSlotSelectionState(List<LoadoutSkillFrameView> frames, bool selected)
    {
        if (frames == null) return;
        for (int i = 0; i < frames.Count; i++)
        {
            LoadoutSkillFrameView frame = frames[i];
            if (frame != null) frame.SetSlotSelected(selected);
        }
    }

    public void PlayInvalidAssignFeedback(SkillLoadoutUnitType unitType, int slotIndex)
    {
        LoadoutSkillFrameView frame = GetLoadoutSlotFrame(unitType, slotIndex);
        if (frame != null)
            frame.PlayInvalidAssignShake();

        ShakeScreen();
    }

    void ShakeScreen()
    {
        if (_rootPanel == null) return;
        var rootRect = _rootPanel.GetComponent<RectTransform>();
        if (rootRect == null) return;
        DOTween.Kill(rootRect, true);
        rootRect.DOShakeAnchorPos(0.28f, strength: 8f, vibrato: 10, randomness: 35f, fadeOut: true);
    }

    LoadoutSkillFrameView GetLoadoutSlotFrame(SkillLoadoutUnitType unitType, int slotIndex)
    {
        List<LoadoutSkillFrameView> frames = unitType == SkillLoadoutUnitType.Book ? _bookSlotFrames : _playerSlotFrames;
        if (slotIndex < 0 || slotIndex >= frames.Count) return null;
        return frames[slotIndex];
    }

    public void ClearCatalog()
    {
        _catalogItems.Clear();
        if (_catalogContainer == null) return;
        for (int i = _catalogContainer.childCount - 1; i >= 0; i--)
            Destroy(_catalogContainer.GetChild(i).gameObject);
    }

    public LoadoutSkillFrameView CreateCatalogItem()
    {
        if (_catalogContainer == null || _skillFramePrefab == null) return null;
        LoadoutSkillFrameView frame = Instantiate(_skillFramePrefab, _catalogContainer);
        _catalogItems.Add(frame);
        return frame;
    }

    public void SetSelectedCatalogSkill(SkillDataSO skill)
    {
        for (int i = 0; i < _catalogItems.Count; i++)
        {
            LoadoutSkillFrameView frame = _catalogItems[i];
            if (frame == null) continue;
            frame.SetCatalogSelected(frame.BoundSkill == skill);
        }
    }

    public void FinalizeCatalogScroll()
    {
        if (_catalogContainer is not RectTransform rt) return;
        LayoutRebuilder.ForceRebuildLayoutImmediate(rt);
        Canvas.ForceUpdateCanvases();
    }

    public void ShowSkillDetails(SkillDataSO skill)
    {
        if (_detailNameText != null) _detailNameText.SetText(skill != null ? skill.SkillName : "-");
        if (_detailDivinityText != null)
            _detailDivinityText.SetText(skill != null ? SkillDivinityUtil.DisplayLabel(skill.Divinity) : "-");
        if (_detailSkillTypeText != null)
            _detailSkillTypeText.SetText(skill != null ? ExplorationLoadoutSkillFilterUtil.DisplayLabel(skill.SkillType) : "-");
        if (_detailDescriptionText != null) _detailDescriptionText.SetText(skill != null ? skill.Description : string.Empty);
        if (_detailPowerText != null) _detailPowerText.SetText(skill != null ? skill.Power.ToString() : "-");
        if (_detailCostText != null)
        {
            if (skill == null) _detailCostText.SetText("-");
            else if (skill.SkillType == SkillType.Passive) _detailCostText.SetText("-");
            else _detailCostText.SetText(skill.Cost.ToString());
        }
        if (_detailRangeText != null)
        {
            if (skill == null) _detailRangeText.SetText("-");
            else if (skill.SkillType == SkillType.SelfBuff) _detailRangeText.SetText("-");
            else _detailRangeText.SetText(skill.Range.ToString("0.##"));
        }
        ApplyDetailVisualLayers(skill);
    }

    private void ApplyDetailVisualLayers(SkillDataSO skill)
    {
        if (skill == null) {
            if (_detailBackgroundImage != null) {
                _detailBackgroundImage.sprite = null;
                _detailBackgroundImage.enabled = false;
            }
            if (_detailFrameImage != null) {
                _detailFrameImage.sprite = null;
                _detailFrameImage.enabled = false;
            }
            if (_detailIconImage != null) {
                _detailIconImage.sprite = null;
                _detailIconImage.enabled = false;
            }
            return;
        }

        if (_visualCatalog != null && _visualCatalog.TryGetLayerSprites(skill.Divinity, skill.SkillType,
                out var bg, out var frame)) {
            if (_detailBackgroundImage != null) {
                _detailBackgroundImage.sprite = bg;
                _detailBackgroundImage.enabled = bg != null;
                if (bg != null) _detailBackgroundImage.color = Color.white;
            }
            if (_detailFrameImage != null) {
                _detailFrameImage.sprite = frame;
                _detailFrameImage.enabled = frame != null;
                if (frame != null) _detailFrameImage.color = Color.white;
            }
        } else {
            if (_detailBackgroundImage != null) {
                _detailBackgroundImage.sprite = null;
                _detailBackgroundImage.enabled = false;
            }
            if (_detailFrameImage != null) {
                _detailFrameImage.sprite = null;
                _detailFrameImage.enabled = false;
            }
        }

        if (_detailIconImage != null) {
            _detailIconImage.sprite = skill.Icon;
            _detailIconImage.enabled = skill.Icon != null;
            if (skill.Icon != null) _detailIconImage.color = Color.white;
        }
    }

    private static void AddPanelOutline(GameObject go, Color outlineColor)
    {
        var o = go.AddComponent<Outline>();
        o.effectColor = outlineColor;
        o.effectDistance = new Vector2(1.5f, -1.5f);
    }

    private static void InsetRect(RectTransform rt, float pixels)
    {
        rt.offsetMin += new Vector2(pixels, pixels);
        rt.offsetMax += new Vector2(-pixels, -pixels);
    }

    private void BuildDebugCanvasIfNeeded()
    {
        EnsureEventSystemExists();

        var canvasRoot = new GameObject("ExplorationLoadoutDebugCanvas");
        canvasRoot.transform.SetParent(transform, false);
        var canvas = canvasRoot.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvasRoot.AddComponent<CanvasScaler>().uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        canvasRoot.AddComponent<GraphicRaycaster>();

        var panel = CreateUiObject("Panel", canvasRoot.transform);
        panel.AddComponent<Image>().color = new Color(0f, 0f, 0f, 0.82f);
        AddPanelOutline(panel, new Color(0.75f, 0.75f, 0.85f, 0.5f));
        var panelRect = panel.GetComponent<RectTransform>();
        panelRect.anchorMin = new Vector2(0.05f, 0.08f);
        panelRect.anchorMax = new Vector2(0.95f, 0.92f);
        panelRect.offsetMin = new Vector2(10f, 10f);
        panelRect.offsetMax = new Vector2(-10f, -10f);

        _rootPanel = panel;
        _playerSlotsContainer = null;
        _bookSlotsContainer = null;

        _closeButton = CreateButton(panel.transform, "CloseButton", "Fechar", new Vector2(0.90f, 0.94f), new Vector2(0.985f, 0.985f));

        var detailsObj = CreateUiObject("Details", panel.transform);
        StretchRect(detailsObj.GetComponent<RectTransform>(), new Vector2(0.60f, 0.38f), new Vector2(0.97f, 0.94f));
        InsetRect(detailsObj.GetComponent<RectTransform>(), 6f);
        detailsObj.AddComponent<Image>().color = new Color(1f, 1f, 1f, 0.07f);
        AddPanelOutline(detailsObj, new Color(1f, 1f, 1f, 0.32f));
        CreateText(detailsObj.transform, "DetailsTitle", "Detalhes", new Vector2(0.04f, 0.88f), new Vector2(0.96f, 0.97f), 22f);
        BuildDetails(detailsObj.transform);

        var playerContainer = CreateUiObject("PlayerSlots", panel.transform);
        StretchRect(playerContainer.GetComponent<RectTransform>(), new Vector2(0.03f, 0.06f), new Vector2(0.49f, 0.35f));
        InsetRect(playerContainer.GetComponent<RectTransform>(), 6f);
        playerContainer.AddComponent<Image>().color = new Color(1f, 1f, 1f, 0.07f);
        AddPanelOutline(playerContainer, new Color(1f, 1f, 1f, 0.32f));
        CreateText(playerContainer.transform, "PlayerSlotsTitle", "Skills Player", new Vector2(0.03f, 0.80f), new Vector2(0.97f, 0.96f), 21f);
        _playerSlotsContainer = BuildLoadoutSlotContainer(playerContainer.transform, "PlayerSlotFrames");

        var bookContainer = CreateUiObject("BookSlots", panel.transform);
        StretchRect(bookContainer.GetComponent<RectTransform>(), new Vector2(0.51f, 0.06f), new Vector2(0.97f, 0.35f));
        InsetRect(bookContainer.GetComponent<RectTransform>(), 6f);
        bookContainer.AddComponent<Image>().color = new Color(1f, 1f, 1f, 0.07f);
        AddPanelOutline(bookContainer, new Color(1f, 1f, 1f, 0.32f));
        CreateText(bookContainer.transform, "BookSlotsTitle", "Skills Livro", new Vector2(0.03f, 0.80f), new Vector2(0.97f, 0.96f), 21f);
        _bookSlotsContainer = BuildLoadoutSlotContainer(bookContainer.transform, "BookSlotFrames");

        var catalogObj = CreateUiObject("Catalog", panel.transform);
        StretchRect(catalogObj.GetComponent<RectTransform>(), new Vector2(0.03f, 0.38f), new Vector2(0.58f, 0.94f));
        InsetRect(catalogObj.GetComponent<RectTransform>(), 6f);
        catalogObj.AddComponent<Image>().color = new Color(1f, 1f, 1f, 0.07f);
        AddPanelOutline(catalogObj, new Color(1f, 1f, 1f, 0.32f));
        CreateText(catalogObj.transform, "CatalogTitle", "Catalogo de Habilidades", new Vector2(0.04f, 0.88f), new Vector2(0.96f, 0.97f), 22f);

        var catalogGrid = CreateUiObject("CatalogContainer", catalogObj.transform);
        StretchRect(catalogGrid.GetComponent<RectTransform>(), new Vector2(0.04f, 0.04f), new Vector2(0.96f, 0.86f));
        var grid = catalogGrid.AddComponent<GridLayoutGroup>();
        grid.cellSize = new Vector2(120f, 120f);
        grid.spacing = new Vector2(8f, 8f);
        grid.constraint = GridLayoutGroup.Constraint.FixedColumnCount;
        grid.constraintCount = 5;
        _catalogContainer = catalogGrid.transform;
    }

    Transform BuildLoadoutSlotContainer(Transform parent, string name)
    {
        var slotsRow = CreateUiObject(name, parent);
        StretchRect(slotsRow.GetComponent<RectTransform>(), new Vector2(0.03f, 0.08f), new Vector2(0.97f, 0.76f));
        var layout = slotsRow.AddComponent<HorizontalLayoutGroup>();
        layout.spacing = 8f;
        layout.childAlignment = TextAnchor.MiddleCenter;
        layout.childControlWidth = false;
        layout.childControlHeight = false;
        layout.childForceExpandWidth = false;
        layout.childForceExpandHeight = false;
        return slotsRow.transform;
    }

